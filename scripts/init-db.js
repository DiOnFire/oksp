import { pool, prefix } from '../src/db.js';

try {
  await pool.query(`CREATE SCHEMA IF NOT EXISTS ${prefix}`);

  await pool.query(`CREATE TABLE IF NOT EXISTS readers(id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,name text NOT NULL);
    CREATE TABLE IF NOT EXISTS books(id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,title text NOT NULL,author text NOT NULL);
    CREATE TABLE IF NOT EXISTS copies(id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,book_id integer NOT NULL REFERENCES books(id),inventory_number text NOT NULL);
    CREATE TABLE IF NOT EXISTS loans(id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,reader_id integer NOT NULL REFERENCES readers(id),
      copy_id integer NOT NULL REFERENCES copies(id),issued_at date NOT NULL,due_date date NOT NULL,returned_at date,
      CHECK(due_date>=issued_at),CHECK(returned_at IS NULL OR returned_at>=issued_at));`);

  console.log(`Schema ${prefix}: ready (4 primary-key indexes only)`);
} finally {
  await pool.end();
}
